#!/usr/bin/env bash
#
# Upload (or delete) every enabled Alertmanager config (data/configs.sh) to
# Mimir with mimirtool. Used by post-start and by the errand. Configs run
# sorted by id; a failing config is reported and the others continue.
# The configs contain receiver credentials: their content is never printed.
#
set -e # exit immediately if a simple command exits with a non-zero status
set -u # report the usage of uninitialized variables
set +x # never trace: configs contain credentials

JOB=mimir-alertmanager

# Load job properties
source /var/vcap/jobs/${JOB}/data/properties.sh

# Setup env vars and folders
source /var/vcap/jobs/${JOB}/packages/bosh-helpers/setup.sh "${JOB}"

# Load function lib
source /var/vcap/jobs/${JOB}/packages/bosh-helpers/lib.sh

MIMIRTOOL=/var/vcap/jobs/${JOB}/packages/mimirtool-linux-amd64/bin/mimirtool
CONFIG_DIR=/var/vcap/data/${JOB}/alertmanager

# All output appended to the log file and echoed to stdout
exec > >(tee -a "${LOG_DIR}/${JOB}.log") 2>&1

finish() {
  local msg="${1}"
  if [ "${FAIL_ON_ERROR}" == "true" ]; then
    echo_log "ERROR: ${msg}"
    exit 1
  fi
  echo_log "WARNING: ${msg} (fail_on_error=false, ignoring)"
  exit 0
}

if [ "${ENABLED}" != "true" ]; then
  echo_log "${JOB} disabled, nothing to do"
  exit 0
fi

if [ "${BOOTSTRAP_ONLY}" == "true" ] && [ "${INSTANCE_BOOTSTRAP}" != "1" ]; then
  echo_log "Not bootstrap instance (${JOB_FULL}) and bootstrap_only=true, skipping"
  exit 0
fi

# Alertmanager configs (generated by BOSH, contains credentials)
source /var/vcap/jobs/${JOB}/data/configs.sh

# Run a command up to RETRIES times with backoff (5s, 10s, 20s, ...)
with_retries() {
  local desc="${1}"
  shift
  local attempt=1
  local delay=5
  while true; do
    echo_log "${desc} (attempt ${attempt}/${RETRIES}) ..."
    if "$@"; then
      return 0
    fi
    if [ "${attempt}" -ge "${RETRIES}" ]; then
      echo_log "${desc} failed after ${RETRIES} attempts"
      return 1
    fi
    echo_log "${desc} failed, retrying in ${delay}s ..."
    sleep "${delay}"
    attempt=$((attempt + 1))
    delay=$((delay * 2))
  done
}

# Process one config. Runs in a subshell (see main loop), so credentials
# exported here do not leak to the other configs. Never print MIMIR_API_KEY.
process_config() {
  local i="${1}"
  local id="${AM_ID[$i]}"
  local mode="${AM_MODE[$i]}"
  local dir="${CONFIG_DIR}/${id}"
  local file="${dir}/alertmanager.yaml"
  local args=(--address="${AM_ADDRESS[$i]}" --id="${AM_TENANT_ID[$i]}")
  local templates=()
  local names=()
  local name
  local n

  # mimirtool reads MIMIR_API_USER / MIMIR_API_KEY from the environment
  unset MIMIR_API_USER MIMIR_API_KEY
  if [ -n "${AM_USER[$i]}" ]; then export MIMIR_API_USER="${AM_USER[$i]}"; fi
  if [ -n "${AM_KEY[$i]}" ]; then export MIMIR_API_KEY="${AM_KEY[$i]}"; fi

  echo_log "[${id}] tenant=${AM_TENANT_ID[$i]} address=${AM_ADDRESS[$i]} mode=${mode}"
  case "${mode}" in
    load)
      mkdir -p "${dir}/templates" || return 1
      echo "${AM_CONFIG[$i]}" | base64 -d > "${file}" || return 1
      local -n contents="AM_TEMPLATES_${i}"
      mapfile -t names < <(echo "${AM_TEMPLATE_NAMES[$i]}" | base64 -d)
      for n in ${contents[@]+"${!contents[@]}"}; do
        name="${names[$n]}"
        echo "${contents[$n]}" | base64 -d > "${dir}/templates/${name}" || return 1
        templates+=("${dir}/templates/${name}")
      done
      echo_log "[${id}] mimirtool alertmanager verify (${#templates[@]} templates)"
      "${MIMIRTOOL}" alertmanager verify "${file}" ${templates[@]+"${templates[@]}"} || return 1
      with_retries "[${id}] mimirtool alertmanager load" \
        "${MIMIRTOOL}" alertmanager load "${args[@]}" "${file}" ${templates[@]+"${templates[@]}"} || return 1
      ;;
    delete)
      with_retries "[${id}] mimirtool alertmanager delete" \
        "${MIMIRTOOL}" alertmanager delete "${args[@]}" || return 1
      ;;
    *)
      echo_log "[${id}] unknown mode '${mode}'"
      return 1
      ;;
  esac
  echo_log "[${id}] ${mode} done"
}

rm -rf "${CONFIG_DIR}"
mkdir -p "${CONFIG_DIR}"
chmod 700 "${CONFIG_DIR}"

for id in ${AM_DISABLED[@]+"${AM_DISABLED[@]}"}; do
  echo_log "[${id}] disabled, skipping (nothing is deleted)"
done

failed=()
for i in ${AM_ID[@]+"${!AM_ID[@]}"}; do
  if ! (process_config "${i}"); then
    echo_log "[${AM_ID[$i]}] FAILED"
    failed+=("${AM_ID[$i]}")
  fi
done

# Do not leave receiver credentials on disk
rm -rf "${CONFIG_DIR}"

if [ "${#failed[@]}" -gt 0 ]; then
  finish "alertmanager configs failed: ${failed[*]}"
fi
echo_log "All alertmanager configs done (${#AM_ID[@]} processed)"
