#!/usr/bin/env bash
#
# Upload every enabled rule set (data/rulesets.sh) to Mimir with mimirtool.
# Used by post-start and by the errand. Rule sets run sorted by id; a failing
# rule set is reported and the others continue.
#
set -e # exit immediately if a simple command exits with a non-zero status
set -u # report the usage of uninitialized variables
set +x # never trace: rule sets contain credentials

JOB=mimir-rules

# Load job properties
source /var/vcap/jobs/${JOB}/data/properties.sh

# Setup env vars and folders
source /var/vcap/jobs/${JOB}/packages/bosh-helpers/setup.sh "${JOB}"

# Load function lib
source /var/vcap/jobs/${JOB}/packages/bosh-helpers/lib.sh

MIMIRTOOL=/var/vcap/jobs/${JOB}/packages/mimirtool-linux-amd64/bin/mimirtool
RULES_DIR=/var/vcap/data/${JOB}/rules

# All output appended to the log file and echoed to stdout
exec > >(tee -a "${LOG_DIR}/${JOB}.log") 2>&1

finish() {
  local msg="${1}"
  if [ "${FAIL_ON_ERROR}" == "true" ]; then
    echo_log "ERROR: ${msg}"
    exit 1
  fi
  echo_log "WARNING: ${msg} (fail_on_error=false, ignoring)"
  exit 0
}

if [ "${ENABLED}" != "true" ]; then
  echo_log "${JOB} disabled, nothing to do"
  exit 0
fi

if [ "${BOOTSTRAP_ONLY}" == "true" ] && [ "${INSTANCE_BOOTSTRAP}" != "1" ]; then
  echo_log "Not bootstrap instance (${JOB_FULL}) and bootstrap_only=true, skipping"
  exit 0
fi

# Rule sets (generated by BOSH, contains credentials)
source /var/vcap/jobs/${JOB}/data/rulesets.sh

# Run a command up to RETRIES times with backoff (5s, 10s, 20s, ...)
with_retries() {
  local desc="${1}"
  shift
  local attempt=1
  local delay=5
  while true; do
    echo_log "${desc} (attempt ${attempt}/${RETRIES}) ..."
    if "$@"; then
      return 0
    fi
    if [ "${attempt}" -ge "${RETRIES}" ]; then
      echo_log "${desc} failed after ${RETRIES} attempts"
      return 1
    fi
    echo_log "${desc} failed, retrying in ${delay}s ..."
    sleep "${delay}"
    attempt=$((attempt + 1))
    delay=$((delay * 2))
  done
}

# Process one rule set. Runs in a subshell with 'set -e' (see main loop): any
# failing command aborts only this rule set. Credentials exported here do not
# leak to the other rule sets. Never print MIMIR_API_KEY.
process_ruleset() {
  local i="${1}"
  local id="${RS_ID[$i]}"
  local namespace="${RS_NAMESPACE[$i]}"
  local mode="${RS_SYNC_MODE[$i]}"
  local file="${RULES_DIR}/${id}.yaml"
  local args=(--address="${RS_ADDRESS[$i]}" --id="${RS_TENANT_ID[$i]}")
  local group

  # mimirtool reads MIMIR_API_USER / MIMIR_API_KEY from the environment
  unset MIMIR_API_USER MIMIR_API_KEY
  if [ -n "${RS_USER[$i]}" ]; then export MIMIR_API_USER="${RS_USER[$i]}"; fi
  if [ -n "${RS_KEY[$i]}" ]; then export MIMIR_API_KEY="${RS_KEY[$i]}"; fi

  echo_log "[${id}] namespace=${namespace} tenant=${RS_TENANT_ID[$i]} address=${RS_ADDRESS[$i]} mode=${mode}"
  echo "${RS_CONTENT[$i]}" | base64 -d > "${file}"

  echo_log "[${id}] mimirtool rules check ${file}"
  "${MIMIRTOOL}" rules check "${file}"
  echo_log "[${id}] mimirtool rules lint --dry-run ${file}"
  "${MIMIRTOOL}" rules lint --dry-run "${file}"

  case "${mode}" in
    load)
      with_retries "[${id}] mimirtool rules load" "${MIMIRTOOL}" rules load "${args[@]}" "${file}"
      ;;
    sync)
      # Always scoped to the rule set namespace: never prune other namespaces
      with_retries "[${id}] mimirtool rules sync --namespaces=${namespace}" "${MIMIRTOOL}" rules sync "${args[@]}" --namespaces="${namespace}" "${file}"
      ;;
    delete-namespace)
      with_retries "[${id}] mimirtool rules delete-namespace ${namespace}" "${MIMIRTOOL}" rules delete-namespace "${args[@]}" "${namespace}"
      ;;
    delete-groups)
      local groups=()
      mapfile -t groups < <(echo "${RS_GROUPS[$i]}" | base64 -d)
      for group in ${groups[@]+"${groups[@]}"}; do
        if [ -z "${group}" ]; then continue; fi
        with_retries "[${id}] mimirtool rules delete ${namespace} '${group}'" "${MIMIRTOOL}" rules delete "${args[@]}" "${namespace}" "${group}"
      done
      ;;
    *)
      echo_log "[${id}] unknown sync_mode '${mode}'"
      return 1
      ;;
  esac
  echo_log "[${id}] ${mode} done"
}

rm -rf "${RULES_DIR}"
mkdir -p "${RULES_DIR}"
chmod 700 "${RULES_DIR}"

for id in ${RS_DISABLED[@]+"${RS_DISABLED[@]}"}; do
  echo_log "[${id}] disabled, skipping (nothing is deleted)"
done

failed=()
for i in ${RS_ID[@]+"${!RS_ID[@]}"}; do
  # Do not use 'if (...)' or '(...) ||': bash disables 'set -e' inside
  # conditionals, so a failing step would not stop the rule set.
  set +e
  (set -e; process_ruleset "${i}")
  rc=$?
  set -e
  if [ "${rc}" -ne 0 ]; then
    echo_log "[${RS_ID[$i]}] FAILED"
    failed+=("${RS_ID[$i]}")
  fi
done

if [ "${#failed[@]}" -gt 0 ]; then
  finish "rule sets failed: ${failed[*]}"
fi
echo_log "All rule sets done (${#RS_ID[@]} processed)"
